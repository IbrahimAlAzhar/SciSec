#!/usr/bin/env python3
"""
_mkjobs_spot.py — write the three PBS jobs (one per reviewer) from ONE template.

    python _mkjobs_spot.py        # -> jobs/job_spot_{gemma3_27b,mistral_24b,qwen3_8b}.pbs

Edit THIS file, not the generated jobs, so the three cannot drift apart.
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
AD_ROOT = "."
CODE = f"{AD_ROOT}/defense_baselines/spotlighting"

JOBS = {
    "gemma3_27b": dict(model="gemma3-27b-it", quant="bnb", wall="140:00:00", mem="100gb",
                       dir="path/to/models/gemma3_27b_it",
                       nice="Gemma-3-27B-IT (4-bit bitsandbytes, as in your runs)"),
    "mistral_24b": dict(model="mistral-small-3.1-24b", quant="bnb", wall="140:00:00",
                        mem="100gb",
                        dir="path/to/models/mistral_small_3_1_24b_instruct",
                        nice="Mistral-Small-3.1-24B (4-bit bitsandbytes, as in your runs)"),
    "qwen3_8b": dict(model="qwen3-8b", quant="none", wall="96:00:00", mem="100gb",
                     dir="path/to/models/qwen3_8b",
                     nice="Qwen3-8B (bf16; thinking disabled through chat_template_kwargs)"),
}

BODY = r'''#!/bin/bash
#PBS -N spot_{tag}
#PBS -l walltime={wall}
#PBS -l select=1:ncpus=8:mpiprocs=1:ngpus=1:mem={mem}
#PBS -j oe
#PBS -o {code}/job_logs/pbs_log_spot_{tag}.txt
#PBS -m abe
#PBS -M anonymous@example.com

# =====================================================================================
# DEFENSE BASELINE — SPOTLIGHTING  (Hines, Lopez, Hall, Zarfati, Zunger & Kiciman, 2024,
# "Defending Against Indirect Prompt Injection Attacks With Spotlighting",
# arXiv:2403.14720; code: spotlighting-datamarking, ported line by line to spotlighting.py)
# Reviewer = {nice}, served with vLLM.
# (generated by _mkjobs_spot.py — edit that file, not this one)
#
# WHAT THE PAPER DOES, AND WHAT THIS JOB DOES
# -------------------------------------------------------------------------------------
#   Paper                                     This job
#   ---------------------------------------  -------------------------------------------
#   task = summarise / Q&A over a document    task = peer-review the manuscript (rating)
#   untrusted data = the document             untrusted data = the manuscript
#   Baseline / +Instructions / +Delimiters /  plain / instruct / delimit / datamark
#   Datamarking / Encoding (Fig. 2-6)         (/ encode with ENCODE=1, datamark_rand)
#   datamark: every whitespace -> marker      identical (index.js markData), dynamic
#   (U+E000 recommended, Sec. 5.4)            PUA marker per document (README: 1-2 PUA
#                                             chars for small/mid-size models)
#   ASR = keyword payload obeyed              rating moved by the attack: Restore /
#                                             Residual / Collateral (your Table 2), dR,
#                                             ASR (dRating>=1 or reject->accept)
#   no detector                               Table-1 row = self-report ADAPTATION: after
#                                             the review, one follow-up turn asks whether
#                                             the marked data tried to steer the review
#
# INPUTS (your three requested results)
#   (a) ours       infer_ladder.load_eval_set — dataset_primary_500.csv +
#                  lim_bb_multimodel_500_data/output_primary500/<model>/seed2/
#                  metrics_detail.csv, id column `id`, seed 0 (= job_c_<model>_infer.pbs)
#   (b) ARGAR/BTR  ab_common.load_pairs (baselines_for_argar_btr): the v8 test pairs
#   (c) combined   both
#
# REVIEWER = the one behind your Table-2 System Defense / SafeReview rows:
#   rl_excise.REVIEWER_SYSTEM, last 24,000 chars, temperature 0, 420 tokens,
#   rl_rewards.extract_json -> rating clamped to [1, 10]. `plain` gives R_0 / R_A.
#
# OUTPUT  {code}/
#   inputs/<model>/docs.jsonl.gz + manifest.json      the frozen documents
#   runs/default/<model>/<variant>/docs.csv           one row per document
#        .../argar_btr/scores.csv + meta.json         -> ab_aggregate.py
#   runs/default/_ladder/<model>/spotlight_<variant>/stage1_detail.csv + summary.json
#                                                     -> category_defense_metrics.py, ft_table.py
#   final/default/<model>/table1_rows.tex  table2_rows.tex   rows to paste
#   final/default/<model>/table_end2end.tex  table1_detection.tex  table2_repair.tex
#   final/default/metrics_long.csv  table2_cross_model.tex  summary.md
#
# COST: ~1,500 distinct manuscripts x 4 variants. The datamarked prompt is ~3x longer
# (a PUA marker is 2-3 tokens per whitespace), hence MAX_LEN=32768. Every review is
# cached on disk: a requeue (same qsub) loses at most the reviews in flight.
#
# SETTINGS — override with  qsub -v NAME=value[,NAME=value] jobs/job_spot_{tag}.pbs
#   (list values use '+', e.g. VARIANTS=plain+datamark, because ',' separates variables)
#   INSPECT=1      no GPU: counts, every prompt, token budget with this model's tokenizer
#   SMOKE=1        4 pairs per source, RUN_TAG=smoke (own folders)
#   VARIANTS       default plain+instruct+delimit+datamark  (+datamark_rand, +encode,
#                  datamark:caret for the paper's '^' marker)
#   ENCODE=1       add the base64 variant (paper: only for the strongest models)
#   MARKER         unicode (default, PUA) | caret | alphanumeric
#   SOURCES        default ours+argar+btr
#   MAX_ROWS       pairs (ours) / pairs per source (ARGAR, BTR); 0 = all
#   RUN_TAG        runs/<tag>/, final/<tag>/
#   DETECT=0       no self-report turn (Table 2 only)
#   MAX_LEN GPU_UTIL QUANT MAX_NUM_SEQS WORKERS   vLLM / client
#   ATTACKED_CSV TEST_CSV ID_COLUMN               (a)'s inputs
#   OURS_DOCS [+ OURS_INDEX]  (a) from a materialised file instead of infer_ladder, e.g.
#                  $V7AB_DIR/inputs/<model>/eval_records.jsonl + eval_index.csv = the exact
#                  documents your SafeReview / System Defense rows were scored on
#   ARGAR_PAIRS_CSV ARGAR_TAG                     (b)'s inputs
#   REVIEWER_PROMPT_FILE   a different reviewer prompt (e.g. v8's); default rl_excise
#   VLLM_URL       an already-running server: skip serving (testing)
# =====================================================================================

set -u
if [[ "${{SPOT_NO_CONDA:-0}}" != "1" ]]; then
    source activate image_lim_vllm_final || {{ echo "[FATAL] could not activate image_lim_vllm_final"; exit 1; }}
fi

export PYTHONUNBUFFERED=1
export TOKENIZERS_PARALLELISM=false
export HF_HOME=${{HF_HOME:-path/to/anonymous/hf_cache}}
export HF_HUB_OFFLINE=1
export TRANSFORMERS_OFFLINE=1
export HF_DATASETS_OFFLINE=1
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True
export no_proxy="127.0.0.1,localhost,::1,${{no_proxy:-}}"
export NO_PROXY="$no_proxy"
unset VLLM_API_KEY          # vLLM 401s every /v1/* request if this merely EXISTS

export AD_ROOT=${{AD_ROOT:-{ad_root}}}
CODE_DIR=${{CODE_DIR:-$AD_ROOT/defense_baselines/spotlighting}}
if [[ -n "${{PBS_O_WORKDIR:-}}" && -f "$PBS_O_WORKDIR/run_spotlight.py" ]]; then
    CODE_DIR="$PBS_O_WORKDIR"; echo "[paths] using the submit directory: $CODE_DIR"
fi
[[ -f "$CODE_DIR/run_spotlight.py" ]] || {{ echo "[FATAL] run_spotlight.py is not in $CODE_DIR"; exit 1; }}
cd "$CODE_DIR" || exit 1
mkdir -p job_logs
rm -rf "$CODE_DIR/__pycache__" 2>/dev/null       # never import a stale .pyc

# ---- where YOUR code lives (every path can be overridden with -v) ---------------------
export FT_CODE_DIR=${{FT_CODE_DIR:-$AD_ROOT/defense/llim_agents_v4_SFT_DPO}}    # infer_ladder.py
export V4_DIR=${{V4_DIR:-$AD_ROOT/defense/llm_agents_v4}}                       # def_dataset.py
export V7AB_DIR=${{V7AB_DIR:-$AD_ROOT/defense/lim_agents_v7_RL_with_argar_btr}} # rl_excise.py
export DEF_ROOT=${{DEF_ROOT:-$AD_ROOT/defense_baselines}}
export ARGAR_DIR=${{ARGAR_DIR:-$DEF_ROOT/baselines_for_argar_btr}}              # ab_common.py
export SPOT_WORK=${{SPOT_WORK:-$CODE_DIR}}

# ---- settings -------------------------------------------------------------------------
MODEL={model}
MODEL_DIR=${{MODEL_DIR:-{model_dir}}}
QUANT=${{QUANT:-{quant}}}
MAX_LEN=${{MAX_LEN:-32768}}
GPU_UTIL=${{GPU_UTIL:-0.90}}
MAX_NUM_SEQS=${{MAX_NUM_SEQS:-32}}
WORKERS=${{WORKERS:-16}}
VARIANTS=${{VARIANTS:-plain+instruct+delimit+datamark}}
MARKER=${{MARKER:-unicode}}
SOURCES=${{SOURCES:-ours+argar+btr}}
MAX_ROWS=${{MAX_ROWS:-0}}
RUN_TAG=${{RUN_TAG:-}}
DETECT=${{DETECT:-1}}
ENCODE=${{ENCODE:-0}}
INSPECT=${{INSPECT:-0}}
SMOKE=${{SMOKE:-0}}
ATTACKED_CSV=${{ATTACKED_CSV:-$AD_ROOT/lim_bb_multimodel_500_data/output_primary500/$MODEL/seed2/metrics_detail.csv}}
TEST_CSV=${{TEST_CSV:-$AD_ROOT/data/final_data/dataset_primary_500.csv}}
ID_COLUMN=${{ID_COLUMN:-id}}
ARGAR_PAIRS_CSV=${{ARGAR_PAIRS_CSV:-}}
export REVIEWER_PROMPT_FILE=${{REVIEWER_PROMPT_FILE:-}}
[[ -n "${{ARGAR_TAG:-}}" ]] && export ARGAR_TAG
if [[ "$SMOKE" == "1" ]]; then
    MAX_ROWS=4; RUN_TAG=${{RUN_TAG:-smoke}}
    echo "[smoke] MAX_ROWS=$MAX_ROWS RUN_TAG=$RUN_TAG (own folders)"
fi
VARIANTS="${{VARIANTS//+/ }}"; VARIANTS="${{VARIANTS//,/ }}"
SOURCES="${{SOURCES//+/ }}"; SOURCES="${{SOURCES//,/ }}"
[[ "$ENCODE" == "1" && " $VARIANTS " != *" encode "* ]] && VARIANTS="$VARIANTS encode"
export RUN_TAG

JOBID="${{PBS_JOBID:-local$$}}"; JOBID="${{JOBID%%.*}}"
RUNLOG=$CODE_DIR/job_logs/run_spot_{tag}${{RUN_TAG:+__$RUN_TAG}}__$JOBID.txt
exec > >(tee -a "$RUNLOG") 2>&1
echo "[log] this transcript: $RUNLOG"

stage () {{ echo; echo "################################################################"; \
           echo "# $*"; echo "# $(date)"; \
           echo "################################################################"; }}
run   () {{ "$@"; local rc=$?; [[ $rc -ne 0 ]] && {{ echo "[FATAL] rc=$rc :: $*"; exit $rc; }}; return 0; }}
soft  () {{ "$@"; local rc=$?; [[ $rc -ne 0 ]] && echo "[warn] rc=$rc :: $*"; return 0; }}

TAGARG=(); [[ -n "$RUN_TAG" ]] && TAGARG=(--run-tag "$RUN_TAG")

# =====================================================================================
stage "ENVIRONMENT — $MODEL"
which python; python --version
nvidia-smi 2>/dev/null | head -12 || echo "[warn] nvidia-smi unavailable"
python -c "import transformers;print('[env] transformers',transformers.__version__)" 2>/dev/null || true
python -c "import vllm;print('[env] vllm',vllm.__version__)" 2>/dev/null || echo "[warn] vllm not importable"
echo "[env] variants: $VARIANTS   marker: $MARKER   sources: $SOURCES   max_rows: $MAX_ROWS   run_tag: ${{RUN_TAG:-default}}   self-report: $DETECT"

# ---- YOUR defence code: taken from these exact folders, never searched for ----------
# Several folders hold same-named files (rl_excise.py in lim_agents_v6_RL AND in v7ab;
# infer_ladder.py in two v4 SFT/DPO folders). The Python side imports each of these from
# the folder named here and checks it; the lines below only show what will be used.
echo "[defence] infer_ladder.py  $FT_CODE_DIR/infer_ladder.py $([[ -f $FT_CODE_DIR/infer_ladder.py ]] && echo OK || echo MISSING)"
echo "[defence] def_dataset.py   $V4_DIR/def_dataset.py $([[ -f $V4_DIR/def_dataset.py ]] && echo OK || echo MISSING)"
echo "[defence] rl_excise.py     $V7AB_DIR/rl_excise.py $([[ -f $V7AB_DIR/rl_excise.py ]] && echo OK || echo MISSING)"
echo "[defence] rl_rewards.py    $V7AB_DIR/rl_rewards.py $([[ -f $V7AB_DIR/rl_rewards.py ]] && echo OK || echo MISSING)"
echo "[defence] ab_common.py     $ARGAR_DIR/ab_common.py $([[ -f $ARGAR_DIR/ab_common.py ]] && echo OK || echo MISSING)"
if [[ -z "$REVIEWER_PROMPT_FILE" && ! -f "$V7AB_DIR/rl_excise.py" ]]; then
    echo "[FATAL] no $V7AB_DIR/rl_excise.py (the Table-2 reviewer prompt). Set V7AB_DIR, or"
    echo "        REVIEWER_PROMPT_FILE=<file with the reviewer system prompt>."
    exit 1
fi

# ---- the ATTACK modules def_dataset needs: EXACTLY job_c_<model>_infer.pbs's search ---
# (same module list, same -maxdepth 2), so the documents are rendered by the same code the
# defense1 rows used. A deeper search picks up stale copies, e.g. no_need/*/align.py.
export PYTHONPATH=$CODE_DIR:$FT_CODE_DIR:$V4_DIR:${{PYTHONPATH:-}}
EXTRA=""
for mod in strategies align runner composite anchors bbmodel tiers coercion objectives \
           agents harness metrics blackbox uca; do
    hits=$(find "$AD_ROOT" -maxdepth 2 -name "$mod.py" -not -path "*/__pycache__/*" \
           -not -path "*/smoke/*" -not -path "$CODE_DIR/*" 2>/dev/null)
    if [[ -z "$hits" ]]; then echo "[locate] $mod.py    not found (may be optional)"; continue; fi
    for h in $hits; do
        d=$(dirname "$h")
        case ":$PYTHONPATH:$EXTRA:" in *":$d:"*) ;; *) EXTRA="$EXTRA:$d" ;; esac
    done
    echo "[locate] $mod.py    $(echo "$hits" | head -1)"
done
export PYTHONPATH="${{PYTHONPATH}}${{EXTRA}}"
for d in $(echo "$EXTRA" | tr ':' ' '); do
    case "$d" in
        *lim_bb_multimodel)      export WB_BB_DIR="$d" ;;
        *lim_uca_hybrid)         export WB_UCA_DIR="$d" ;;
        *lim_track3*mech*)       export WB_T35_DIR="$d" ;;
        *lim_composite_attack)   export WB_COMP_DIR="$d" ;;
        *feas_dis_search*)       export WB_FEAS_DIR="$d" ;;
        *lim_white_black_transf) export WB_SRC_DIR="$d" ;;
    esac
done
[[ -f "$TEST_CSV" ]] || {{ echo "[FATAL] $TEST_CSV not found"; exit 1; }}
if [[ " $SOURCES " == *" ours "* && ! -f "$ATTACKED_CSV" && -z "${{OURS_DOCS:-}}" ]]; then
    echo "[FATAL] $ATTACKED_CSV not found. Seeds present:"
    ls -1 "$(dirname "$(dirname "$ATTACKED_CSV")")" 2>/dev/null | sed 's/^/          /'
    exit 1
fi

# =====================================================================================
stage "[0] self-test (CPU, mock vLLM server, fake benchmark modules)"
run python -u spot_selftest.py

# =====================================================================================
stage "[1] INPUTS — (a) infer_ladder.load_eval_set, (b) ab_common.load_pairs -> one frozen file"
IN=(--model "$MODEL" --sources $SOURCES --max-rows "$MAX_ROWS" --benign-csv "$TEST_CSV"
    --attacked-csv "$ATTACKED_CSV" --id-column "$ID_COLUMN" --seed 0 ${{TAGARG[@]+"${{TAGARG[@]}}"}})
[[ -n "$ARGAR_PAIRS_CSV" ]] && IN+=(--argar-pairs-csv "$ARGAR_PAIRS_CSV")
[[ -n "${{OURS_DOCS:-}}" ]] && IN+=(--ours-docs "$OURS_DOCS")
[[ -n "${{OURS_INDEX:-}}" ]] && IN+=(--ours-index "$OURS_INDEX")
[[ "${{FORCE_INPUTS:-0}}" == "1" ]] && IN+=(--force)
run python -u run_spotlight.py inputs "${{IN[@]}}"

# =====================================================================================
stage "[2] INSPECT — every prompt, and the token budget with $MODEL's own tokenizer (no GPU)"
SP=(--variants $VARIANTS --marker "$MARKER" ${{TAGARG[@]+"${{TAGARG[@]}}"}})
[[ -n "$REVIEWER_PROMPT_FILE" ]] && SP+=(--prompt-file "$REVIEWER_PROMPT_FILE")
soft python -u run_spotlight.py inspect --model "$MODEL" "${{SP[@]}}" \
    --tokenizer "$MODEL_DIR" --max-len "$MAX_LEN"
if [[ "$INSPECT" == "1" ]]; then echo "[inspect] INSPECT=1 — stopping before the GPU"; exit 0; fi

# =====================================================================================
stage "[3] serve $MODEL with vLLM (max_len $MAX_LEN, prefix caching: the self-report turn reuses the review's prefix)"
VPID=""
if [[ -z "${{VLLM_URL:-}}" ]]; then
    VDIR=$CODE_DIR/job_logs/_vllm_{tag}; mkdir -p "$VDIR"
    VLOG=$VDIR/vllm_server_$JOBID.log
    run bash serve_vllm.sh "$MODEL_DIR" auto "$QUANT" "$MAX_LEN" "$GPU_UTIL" "$VLOG" \
        --max-num-seqs "$MAX_NUM_SEQS" --enable-prefix-caching
    PORT="$(cat "${{VLOG}}.port")"
    export VLLM_URL="http://127.0.0.1:${{PORT}}/v1"
    VPID="$(cat "$VDIR"/vllm_${{PORT}}_$(hostname -s).pid 2>/dev/null || true)"
    trap '[[ -n "${{VPID:-}}" ]] && kill "$VPID" 2>/dev/null; echo "[cleanup] vLLM stopped"' EXIT
    SERVED="$MODEL_DIR"
else
    echo "[serve] using the server already at $VLLM_URL"
    SERVED="${{VLLM_MODEL:-$MODEL_DIR}}"
fi
echo "[serve] $VLLM_URL   served-model-name = $SERVED"

# =====================================================================================
stage "[4] REVIEW — every manuscript under every variant ($VARIANTS)"
RV=(--model "$MODEL" --vllm-url "$VLLM_URL" --served "$SERVED" --workers "$WORKERS"
    "${{SP[@]}}" --tokenizer "$MODEL_DIR")
[[ "$DETECT" == "1" ]] || RV+=(--no-detect)
run python -u run_spotlight.py review "${{RV[@]}}"
[[ -n "${{VLOG:-}}" ]] && {{ grep -i "prefix cache hit rate" "$VLOG" | tail -n 1 | sed 's/^/[vllm] /' || true; }}

# =====================================================================================
stage "[5] REPORT — every reviewer finished so far -> Table 1 / Table 2 rows"
soft python -u run_spotlight.py report ${{TAGARG[@]+"${{TAGARG[@]}}"}}

stage "DONE — $MODEL"
echo "  $CODE_DIR/final/${{RUN_TAG:-default}}/$MODEL/table2_rows.tex   (Table 2: Res / Resd / Col)"
echo "  $CODE_DIR/final/${{RUN_TAG:-default}}/$MODEL/table1_rows.tex   (Table 1: self-report adaptation)"
echo "  $CODE_DIR/final/${{RUN_TAG:-default}}/$MODEL/table_end2end.tex (dR, ASR, Restore, ..., WCov)"
echo "  $CODE_DIR/final/${{RUN_TAG:-default}}/summary.md"
echo "  $RUNLOG"
date
'''


def main() -> None:
    os.makedirs(os.path.join(HERE, "jobs"), exist_ok=True)
    for tag, j in JOBS.items():
        txt = BODY.format(tag=tag, wall=j["wall"], mem=j["mem"], code=CODE, ad_root=AD_ROOT,
                          nice=j["nice"], model=j["model"], model_dir=j["dir"],
                          quant=j["quant"])
        p = os.path.join(HERE, "jobs", f"job_spot_{tag}.pbs")
        with open(p, "w") as f:
            f.write(txt)
        os.chmod(p, 0o755)
        print(f"[mkjobs] {p}")


if __name__ == "__main__":
    main()
