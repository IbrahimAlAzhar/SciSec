#!/usr/bin/env python3
"""
_mkjobs_ab.py — write the PBS jobs (and .txt copies) for the ARGAR/BTR baselines.

    python _mkjobs_ab.py          # -> jobs/job_ab_{all,detectors,llm,existing,aggregate}.pbs

Edit THIS file, not the generated jobs. All jobs share one body; they differ only in the
default STAGES and the resources they ask for.
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))

JOBS = {
    "all":       dict(stages="d1 d3 protectai piguard d7 paperguard agg", gpu=1, mem="100gb", wall="24:00:00",
                      what="every baseline, then the table (gemma is started only for d7/paperguard)"),
    "detectors": dict(stages="d1 d3 protectai piguard agg", gpu=1, mem="64gb", wall="08:00:00",
                      what="D1, D3 regex/PPL/combined, D6 ProtectAI, PIGuard (no LLM)"),
    "llm":       dict(stages="d7 paperguard agg", gpu=1, mem="100gb", wall="24:00:00",
                      what="D7 LlamaFirewall AlignmentCheck + PaperGuard, gemma3-27b served here"),
    "existing":  dict(stages="existing agg", gpu=1, mem="100gb", wall="24:00:00",
                      what="your ORIGINAL defense_baselines scripts, unchanged, on ARGAR/BTR (SCRIPTS=...)"),
    "aggregate": dict(stages="agg", gpu=0, mem="16gb", wall="01:00:00",
                      what="rebuild the table from whatever has been scored"),
}

BODY = r'''#!/bin/bash
#PBS -N ab_{name}
#PBS -l walltime={wall}
#PBS -l select=1:ncpus=8:mpiprocs=1{gpu_sel}:mem={mem}
#PBS -j oe
#PBS -m abe
#PBS -M anonymous@example.com
# =====================================================================================
# Defense baselines on ARGAR + BTR — {what}
# (generated by _mkjobs_ab.py; edit that file, not this one)
#
#   qsub jobs/job_ab_{name}.pbs
#   qsub -v MAX_ROWS=5,RUN_TAG=pilot5 jobs/job_ab_{name}.pbs        # 5 pairs per source first
#
# CONTROLS (-v NAME=value; for several, export them first and pass -v with NAMES only,
# because a comma inside a value breaks qsub -v):
#   STAGES       default "{stages}"
#                d1 d3 protectai piguard d7 paperguard existing agg
#   MAX_ROWS     pairs per source (0 = all: ARGAR 55, BTR 240)
#   RUN_TAG      output/<tag>/ and final/<tag>/   (default: default)
#   SOURCES      default "argar btr"   (add insertion to re-score the insertion set too)
#   SUBSET       test (default, the v8 test half) | full
#   THRESHOLDS   insertion (default, frozen from each detector's insertion run) | own
#   PPL_MODEL DEBERTA PIGUARD   local model dirs (found under $MODELS_DIR if unset)
#   NO_PPL=1     regex only in D3
#   PG_REGISTRY  PaperGuard registry file (searched for if unset)
#   EMBEDDER     auto | tfidf | sbert:<dir>     (PaperGuard retrieval)
#   AC_INCLUDE_DOC=1   give AlignmentCheck the manuscript as a tool observation
#   SCRIPTS      for the `existing` stage: e.g. "d7_llamafirewall.py paperguard_defense.py"
#   START_GEMMA=1      start gemma for the `existing` stage too
#   MAX_LEN QUANT GPU_UTIL   gemma server (default 16384, bnb, 0.88)
#
# NO `set -o pipefail`, no `set -e`: run() stops the job naming the failed command,
# soft() only warns. API keys are never in this file (nothing here needs one).
# =====================================================================================
set -u
source activate image_lim_vllm_final || {{ echo "[FATAL] conda env activation failed"; exit 1; }}

export PYTHONUNBUFFERED=1
export TOKENIZERS_PARALLELISM=false
export HF_HOME=path/to/anonymous/hf_cache
export HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 HF_DATASETS_OFFLINE=1
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True
export no_proxy="127.0.0.1,localhost,::1,${{no_proxy:-}}"
export NO_PROXY="$no_proxy"
unset VLLM_API_KEY
[[ -f "$HOME/.keys" ]] && source "$HOME/.keys"

export AD_ROOT=.
export MODELS_DIR=path/to/anonymous/models
export DEF_ROOT=$AD_ROOT/defense_baselines
CODE_DIR=$DEF_ROOT/baselines_for_argar_btr
[[ -f "$CODE_DIR/ab_common.py" ]] || {{ echo "[FATAL] ab_common.py is not in $CODE_DIR"; exit 1; }}
[[ -f "$DEF_ROOT/common.py" ]] || {{ echo "[FATAL] $DEF_ROOT/common.py missing (the original baselines)"; exit 1; }}
cd "$CODE_DIR" || exit 1
rm -rf "$CODE_DIR/__pycache__" 2>/dev/null

STAGES="${{STAGES:-{stages}}}"
MAX_ROWS="${{MAX_ROWS:-0}}"
export RUN_TAG="${{RUN_TAG:-}}"
SOURCES="${{SOURCES:-argar btr}}"
SUBSET="${{SUBSET:-test}}"
THRESHOLDS="${{THRESHOLDS:-insertion}}"
PPL_MODEL="${{PPL_MODEL:-}}"; DEBERTA="${{DEBERTA:-}}"; PIGUARD="${{PIGUARD:-}}"
EMBEDDER="${{EMBEDDER:-auto}}"
MAX_LEN="${{MAX_LEN:-16384}}"; QUANT="${{QUANT:-bnb}}"; GPU_UTIL="${{GPU_UTIL:-0.88}}"

JOBID="${{PBS_JOBID:-local$$}}"; JOBID="${{JOBID%%.*}}"
LOGDIR="$CODE_DIR/job_logs/$(echo "$STAGES" | tr ' ' '-')${{RUN_TAG:+__$RUN_TAG}}__$JOBID"
mkdir -p "$LOGDIR"
exec > >(tee -a "$LOGDIR/output.txt") 2> >(tee -a "$LOGDIR/error.txt" >&2)
{{ echo "job $JOBID  $(date)"; echo "stages: $STAGES"; echo "max_rows=$MAX_ROWS run_tag=${{RUN_TAG:-default}}"
   echo "sources=$SOURCES subset=$SUBSET thresholds=$THRESHOLDS"; }} > "$LOGDIR/meta.txt"
echo "[log] $LOGDIR/{{output,error,meta}}.txt   (an empty error.txt means no errors)"

stage () {{ echo; echo "################################################################"; echo "# $*"; echo "# $(date)"; echo "################################################################"; }}
run ()  {{ "$@"; local rc=$?; if [[ $rc -ne 0 ]]; then echo "[FATAL] rc=$rc :: $*"; exit $rc; fi; return 0; }}
soft () {{ "$@"; local rc=$?; if [[ $rc -ne 0 ]]; then echo "[warn] rc=$rc :: $*" >&2; fi; return 0; }}
has ()  {{ [[ " $STAGES " == *" $1 "* ]]; }}

COMMON=(--sources $SOURCES --subset "$SUBSET" --max-rows "$MAX_ROWS" --thresholds "$THRESHOLDS")
[[ -n "$RUN_TAG" ]] && COMMON+=(--run-tag "$RUN_TAG")

VPID=""
cleanup () {{ [[ -n "$VPID" ]] && kill "$VPID" 2>/dev/null; }}
trap cleanup EXIT
start_gemma () {{
    [[ -n "${{VLLM_URL:-}}" ]] && return 0
    stage "[gemma] starting gemma3-27b-it (vLLM, $QUANT, max_len $MAX_LEN)"
    local L="$LOGDIR/vllm.log"
    run bash "$CODE_DIR/serve_gemma.sh" "$L" "$MAX_LEN" "$GPU_UTIL" "$QUANT"
    export VLLM_URL="http://127.0.0.1:$(cat "$L.port")"
    VPID=$(cat "$L.pid")
    echo "[gemma] VLLM_URL=$VLLM_URL"
}}

stage "[env]"
which python; python --version
nvidia-smi 2>/dev/null | head -12 || echo "[info] no GPU visible"
python - <<'P'
import ab_common as A
print("[paths] test pairs :", A.test_pairs_path(), "(exists)" if __import__("os").path.exists(A.test_pairs_path()) else "(MISSING -> rebuilt from raw ARGAR/BTR)")
print("[paths] insertion  :", A.INSERTION_OUT)
print("[paths] v8 replay  :", A.V8_DIR)
P

if has d1; then
    stage "[D1] flag nothing / flag everything"
    run python -u ab_d1_trivial.py "${{COMMON[@]}}"
fi
if has d3; then
    stage "[D3] regex / GPT-2 perplexity / combined"
    A3=(); [[ -n "$PPL_MODEL" ]] && A3+=(--ppl-model "$PPL_MODEL"); [[ "${{NO_PPL:-0}}" == "1" ]] && A3+=(--no-ppl)
    soft python -u ab_d3_ppl_regex.py "${{COMMON[@]}}" "${{A3[@]}}"
fi
if has protectai; then
    stage "[D6] ProtectAI DeBERTa-v3 prompt-injection-v2"
    A6=(); [[ -n "$DEBERTA" ]] && A6+=(--model "$DEBERTA")
    soft python -u ab_classifiers.py --detector protectai "${{COMMON[@]}}" "${{A6[@]}}"
fi
if has piguard; then
    stage "[PIGuard] leolee99/PIGuard"
    AP=(); [[ -n "$PIGUARD" ]] && AP+=(--model "$PIGUARD")
    soft python -u ab_classifiers.py --detector piguard "${{COMMON[@]}}" "${{AP[@]}}"
fi
if has d7; then
    start_gemma
    stage "[D7] LlamaFirewall AlignmentCheck, AC-only, replay (auditor: gemma3-27b)"
    A7=(); [[ "${{AC_INCLUDE_DOC:-0}}" == "1" ]] && A7+=(--ac-include-doc)
    soft python -u ab_d7_llamafirewall.py "${{COMMON[@]}}" "${{A7[@]}}"
fi
if has paperguard; then
    start_gemma
    stage "[PaperGuard] released registry + gemma3-27b verifier"
    AG=(--embedder "$EMBEDDER"); [[ -n "${{PG_REGISTRY:-}}" ]] && AG+=(--registry "$PG_REGISTRY")
    soft python -u ab_paperguard.py "${{COMMON[@]}}" "${{AG[@]}}"
fi
if has existing; then
    [[ "${{START_GEMMA:-0}}" == "1" ]] && start_gemma
    export SOURCES SUBSET MAX_ROWS
    for S in ${{SCRIPTS:-}}; do
        stage "[existing] $S (original script, ARGAR/BTR data via run_existing.py)"
        soft python -u run_existing.py "$S"
    done
    [[ -z "${{SCRIPTS:-}}" ]] && echo "[existing] SCRIPTS is empty; nothing to run"
fi
if has agg; then
    stage "[AGG] table"
    AA=(); [[ -n "$RUN_TAG" ]] && AA+=(--run-tag "$RUN_TAG")
    run python -u ab_aggregate.py "${{AA[@]}}"
fi

echo
echo "==================================================================="
echo "DONE  $(date)"
echo "  per baseline : $CODE_DIR/output/${{RUN_TAG:-default}}/<baseline>/output.txt"
echo "  table        : $CODE_DIR/final/${{RUN_TAG:-default}}/table_argar_btr.tex"
echo "  logs         : $LOGDIR"
echo "==================================================================="
'''


def main() -> int:
    os.makedirs(os.path.join(HERE, "jobs"), exist_ok=True)
    for name, j in JOBS.items():
        txt = BODY.format(name=name, wall=j["wall"], mem=j["mem"], stages=j["stages"],
                          what=j["what"], gpu_sel=f":ngpus={j['gpu']}" if j["gpu"] else "")
        for ext in (".pbs", ".txt"):
            p = os.path.join(HERE, "jobs", f"job_ab_{name}{ext}")
            with open(p, "w") as f:
                f.write(txt)
            os.chmod(p, 0o755)
        print(f"[jobs] jobs/job_ab_{name}.pbs (+ .txt)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
