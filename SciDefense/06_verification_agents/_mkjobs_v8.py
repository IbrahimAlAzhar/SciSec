def render(s: str, **kw) -> str:
    for k, v in kw.items():
        s = s.replace(f"@@{k}@@", v)
    assert "@@" not in s, [l for l in s.splitlines() if "@@" in l][:3]
    return s


def build_jobs():
    """[(name, text)] for the cluster PBS files; _mkjobs_ares.py transforms these."""
    out = []
    for m in LOCAL:
        txt = (render(COMMON_HEAD, JOBNAME=f"v8_{m['short']}", GPU="ngpus=1:", MEM=m["mem"],
                      MODEL=m["model"], MODEL_DIR=m["model_dir"], QUANT=m["quant"],
                      TAG=m["tag"], NOTE=m["note"], DEFAULT_MODE="all", PLAN_API="")
               + SERVER_FUNCS + FINISH + EVAL_DONE + SELFTEST + INPUTS_LOCAL + LOCAL_BODY
               + TABLE)
        out.append((f"job_v8_{m['short']}", txt))
    gpt = (render(COMMON_HEAD, JOBNAME="v8_gpt4omini", GPU="", MEM="24gb", MODEL="gpt-4o-mini",
                  MODEL_DIR="", QUANT="api", TAG="gpt_4o_mini",
                  NOTE="API model: zero-shot only; CONCURRENCY also bounds requests/sec",
                  DEFAULT_MODE="zeroshot", PLAN_API="--api")
           + FINISH + EVAL_DONE + SELFTEST + GPT_BODY + TABLE)
    out.append(("job_v8_gpt4omini", gpt))
    return out


def main() -> int:
    jobs = os.path.join(HERE, "jobs")
    os.makedirs(jobs, exist_ok=True)
    for name, txt in build_jobs():
        for ext in (".pbs", ".txt"):
            p = os.path.join(jobs, name + ext)
            with open(p, "w", newline="\n") as f:
                f.write(txt)
        print(f"[jobs] {name}.pbs  ({txt.count(chr(10))} lines)")
    return 0


