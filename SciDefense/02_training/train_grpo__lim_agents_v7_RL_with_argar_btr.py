# ======================================================================================
# the training example
# ======================================================================================
@dataclass
class Turn:
    """One agent utterance with the advantage its credit rule assigned it."""
    doc_id: str
    agent: str
    messages: List[Dict]
    completion: str
    adv: float
    adv_inter: float = 0.0
    adv_intra: float = 0.0
    group_index: int = 0
    reward: float = 0.0
    # filled by the trainer
    old_logprob: Optional[float] = None


def load_turns(roll_dir: str, *, credit_override: str = "",
               agents: Sequence[str] = ()) -> Tuple[List[Turn], Dict]:
    """
    Join rollouts.jsonl (rewards + credit) with turns.jsonl (prompts + completions).

    Joined on (doc_id, group_index, agent), which is unique by construction. Groups the
    credit rule marked `dropped` are EXCLUDED here rather than given zero advantage: a
    zero-advantage example still costs a forward and a backward pass and contributes
    nothing but numerical noise to the gradient accumulation.
    """
    rp = os.path.join(roll_dir, "rollouts.jsonl")
    tp = os.path.join(roll_dir, "turns.jsonl")
    for p in (rp, tp):
        if not os.path.exists(p):
            raise SystemExit(f"[FATAL] {p} not found — run v7_score_rollouts.py first")

    meta: Dict[Tuple[str, int], Dict] = {}
    stats = {"n_rollouts": 0, "n_dropped": 0, "rules": defaultdict(int)}
    for line in open(rp):
        if not line.strip():
            continue
        d = json.loads(line)
        stats["n_rollouts"] += 1
        stats["rules"][d.get("credit_rule", "?")] += 1
        if d.get("group_dropped"):
            stats["n_dropped"] += 1
            continue
        meta[(d["doc_id"], int(d.get("group_index", 0)))] = d

    keep = set(agents) if agents else None
    out: List[Turn] = []
    n_unmatched = 0
    for line in open(tp):
        if not line.strip():
            continue
        d = json.loads(line)
        if keep and d["agent"] not in keep:
            continue
        m = meta.get((d["doc_id"], int(d.get("group_index", 0))))
        if m is None:
            n_unmatched += 1
            continue
        if not str(d.get("completion") or "").strip():
            continue                     # a failed call has nothing to learn from
        ag = d["agent"]
        inter = float((m.get("credit_inter") or {}).get(ag, 0.0))
        intra = float((m.get("credit_intra") or {}).get(ag, 0.0))
        w = float(m.get("credit_weight_intra", 0.0))
        out.append(Turn(doc_id=d["doc_id"], agent=ag, messages=d["messages"],
                        completion=d["completion"],
                        adv=(1.0 - w) * inter + w * intra,
                        adv_inter=inter, adv_intra=intra,
                        group_index=int(d.get("group_index", 0)),
                        reward=float(m.get("reward", 0.0))))
    stats["n_turns"] = len(out)
    stats["n_unmatched"] = n_unmatched
    stats["rules"] = dict(stats["rules"])
    print(f"[data] {stats['n_rollouts']} rollouts "
          f"({stats['n_dropped']} in no-signal groups, excluded) -> {len(out)} turns")
    if n_unmatched:
        print(f"[data] {n_unmatched} turns had no matching rollout — usually a partially "
              f"written rollouts.jsonl from an interrupted job. They are skipped.")
    by_agent = defaultdict(int)
    adv_by_agent = defaultdict(list)
    for t in out:
        by_agent[t.agent] += 1
        adv_by_agent[t.agent].append(t.adv)
    print(f"  {'agent':<16}{'turns':>8}{'mean adv':>11}{'std adv':>10}")
    for a in sorted(by_agent):
        v = adv_by_agent[a]
        mu = sum(v) / len(v)
        sd = math.sqrt(sum((x - mu) ** 2 for x in v) / max(1, len(v) - 1))
        print(f"  {a:<16}{by_agent[a]:>8}{mu:>11.3f}{sd:>10.3f}")
        if sd < 1e-3:
            print(f"    ^ this agent received NO differentiated credit. With the "
                  f"`uniform` rule that is expected; with any other rule it means the "
                  f"agent behaved identically across the group.")
    return out, stats


# ======================================================================================
# tokenisation
# ======================================================================================
def render(tok, messages: List[Dict], completion: str, *, max_len: int
           ) -> Optional[Tuple[List[int], int]]:
    """
    (input_ids, completion_length).

    The prompt is rendered with add_generation_prompt=True and the completion appended as
    raw tokens. Rendering the completion through the chat template instead would append
    an end-of-turn marker the model never actually generated, and the log-probability of
    a token the policy did not emit is not a term the objective is entitled to.

    TRUNCATION IS FROM THE LEFT. The manuscript region sits at the front of the prompt and
    the schema block and the completion at the end; cutting from the right would remove
    the output format contract and the answer itself.
    """
    try:
        prompt_ids = tok.apply_chat_template(messages, tokenize=True,
                                             add_generation_prompt=True)
    except Exception as e:
        print(f"[tok] chat template failed: {type(e).__name__}: {e}")
        return None
    comp_ids = tok(completion, add_special_tokens=False).input_ids
    if not comp_ids:
        return None
    if len(prompt_ids) + len(comp_ids) > max_len:
        room = max_len - len(comp_ids)
        if room < 64:
            # The completion alone nearly fills the window. Training on a prompt stub
            # would teach the agent to answer without having seen the manuscript.
            return None
        prompt_ids = prompt_ids[-room:]
    return list(prompt_ids) + list(comp_ids), len(comp_ids)


# ======================================================================================
# log-probabilities
# ======================================================================================
def seq_logprobs(model, input_ids, attn, comp_len: int, *, torch, keep_supported: bool):
    """
    Per-token log-probabilities of the COMPLETION tokens only.

    `logits_to_keep` is the memory fix, and on gemma3 it is the difference between
    running and not running. The vocabulary is 262,144; at 4096 positions the full logits
    tensor is 2 GiB in bf16 and the fp32 log-softmax on top of it is another 4. Restricting
    to the ~640 completion positions turns that into about 0.9 GiB total. Older
    transformers spell the argument `num_logits_to_keep`; both are tried once at startup
    and the answer cached.
    """
    kw = {}
    if keep_supported:
        kw["logits_to_keep"] = comp_len + 1
    out = model(input_ids=input_ids, attention_mask=attn, use_cache=False, **kw)
    logits = out.logits.float()
    # positions predicting the completion tokens
    if keep_supported:
        logits = logits[:, :-1, :]
        targets = input_ids[:, -comp_len:]
    else:
        logits = logits[:, -comp_len - 1:-1, :]
        targets = input_ids[:, -comp_len:]
    lp = torch.log_softmax(logits, dim=-1)
    return lp.gather(-1, targets.unsqueeze(-1)).squeeze(-1)      # (1, comp_len)


def _probe_logits_to_keep(model, torch) -> bool:
    import inspect
    try:
        sig = inspect.signature(model.forward)
        if "logits_to_keep" in sig.parameters:
            return True
        if "num_logits_to_keep" in sig.parameters:
            print("[mem] this transformers spells it `num_logits_to_keep`; the newer "
                  "`logits_to_keep` is absent. Falling back to full logits, which on a "
                  "262k-vocab model needs ~6 GiB more. Lower --max-seq-len if it OOMs.")
            return False
    except (TypeError, ValueError):
        pass
    print("[mem] could not inspect forward(); assuming no logits_to_keep support.")
    return False


# ======================================================================================
# the trainer
# ======================================================================================
def train(turns: List[Turn], model_key: str, out_dir: str, *,
          init_adapter: str = "", cfg: C.GRPOConfig = C.GRPO,
          intra_steps: int = 1, max_steps: int = 0, log_every: int = 10,
          dry_run: bool = False) -> Dict:
    import torch
    from peft import LoraConfig, PeftModel, get_peft_model
    from transformers import AutoTokenizer, get_cosine_schedule_with_warmup

    spec = C.MODELS[model_key]
    print(f"\n[load] {spec.path}  4bit={spec.load_4bit}")
    device_map = FM.pick_device_map()
    tok = AutoTokenizer.from_pretrained(spec.path, trust_remote_code=True)
    if tok.pad_token_id is None:
        tok.pad_token = tok.eos_token
    # rl_load instead of FM.load_base: one from_pretrained call (FM's dtype-kwarg retry
    # reads all 12 shards, fails, and reads them again without freeing the first copy —
    # two 4-bit copies of a 27B is 31 of 39.5 GiB), and sdpa instead of eager, which on
    # gemma3-27b at L=2048 is the difference between ~1 GiB and ~50 GiB of attention.
    # See rl_load.py for why sdpa is correct on gemma3 and wrong on gemma2.
    import rl_load as RL
    base = RL.load_base_once(spec.path, quant=C.bnb_config(spec),
                             dtype=C.compute_dtype(), device_map=device_map,
                             attn_implementation=RL.attn_default())
    FM.report_device_map(base)
    FM.set_use_cache(base, False)
    print(RL.cuda_report("after base load"))

    if init_adapter and os.path.isdir(init_adapter):
        print(f"[lora] continuing from {init_adapter}")
        model = PeftModel.from_pretrained(base, init_adapter, is_trainable=True)
    else:
        if init_adapter:
            print(f"[lora] {init_adapter} not found — starting a FRESH adapter.")
            print(f"[lora] That is a legitimate ablation (RL from the base policy) but it "
                  f"is NOT the row labelled 'SFT then RL'. Check the stage name.")
        targets = FM.lora_targets(base, cfg.target_modules)
        model = get_peft_model(base, LoraConfig(
            r=cfg.lora_r, lora_alpha=cfg.lora_alpha, lora_dropout=cfg.lora_dropout,
            bias="none", task_type="CAUSAL_LM", target_modules=targets))
    model.train()
    try:
        model.print_trainable_parameters()
    except Exception:
        pass
    if cfg.grad_checkpointing:
        # use_reentrant=False: the reentrant checkpoint wrapper needs an input that
        # requires grad, and a 4-bit embedding does not provide one.
        try:
            model.gradient_checkpointing_enable(
                gradient_checkpointing_kwargs={"use_reentrant": False})
        except TypeError:
            model.gradient_checkpointing_enable()
        except Exception as e:
            print(f"[mem] gradient checkpointing unavailable: {type(e).__name__}: {e}")
        try:
            model.enable_input_require_grads()
        except Exception:
            pass
        FM.set_use_cache(model, False)
        print(RL.cuda_report("after checkpointing"))

    keep_supported = _probe_logits_to_keep(model, torch)
    dev = next(model.parameters()).device

    # ---- tokenise up front, so a template failure surfaces before the first step -----
    prepared: List[Tuple[Turn, List[int], int]] = []
    n_drop_tok = 0
    for t in turns:
        r = render(tok, t.messages, t.completion, max_len=cfg.max_seq_len)
        if r is None:
            n_drop_tok += 1
            continue
        prepared.append((t, r[0], r[1]))
    print(f"[tok] {len(prepared)} turns tokenised, {n_drop_tok} dropped "
          f"(empty completion, or no room for the prompt at "
          f"--max-seq-len {cfg.max_seq_len})")
    if not prepared:
        raise SystemExit("[FATAL] nothing left to train on after tokenisation.")
    lens = sorted(len(x[1]) for x in prepared)
    print(f"[tok] sequence length: median {lens[len(lens)//2]}, "
          f"p90 {lens[int(0.9*len(lens))]}, max {lens[-1]}")
    trunc = sum(1 for _t, ids, _c in prepared if len(ids) >= cfg.max_seq_len)
    if trunc:
        print(f"[tok] {trunc} ({100*trunc/len(prepared):.1f}%) hit the length cap and "
              f"lost the head of the manuscript. Above ~20% the policy is being trained "
              f"on documents it cannot see the start of.")

    # M-GRPO's decoupling: the local term gets more optimiser steps than the shared one.
    # Implemented by REPEATING worker turns with the intra advantage only -- which is what
    # "more steps on the intra objective" means when both share one optimiser.
    # (index into `prepared`, turn, ids, completion length, advantage). The index is what
    # lets a turn reuse its CACHED reference log-probs below even when M-GRPO schedules
    # the same turn several times.
    schedule: List[Tuple[int, Turn, List[int], int, float]] = []
    for j, (t, ids, clen) in enumerate(prepared):
        schedule.append((j, t, ids, clen, t.adv))
        if intra_steps > 1 and t.agent != C.MASTER and abs(t.adv_intra) > 1e-6:
            for _ in range(intra_steps - 1):
                schedule.append((j, t, ids, clen, t.adv_intra))
    if intra_steps > 1:
        print(f"[mgrpo] decoupled updates: worker turns get {intra_steps} steps on the "
              f"local advantage, master turns 1. {len(schedule)} total steps vs "
              f"{len(prepared)} turns.")

    rng = random.Random(cfg.seed)
    rng.shuffle(schedule)
    if max_steps:
        schedule = schedule[:max_steps * cfg.grad_accum]

    n_updates = max(1, len(schedule) // cfg.grad_accum)
    opt = torch.optim.AdamW([p for p in model.parameters() if p.requires_grad],
                            lr=cfg.lr, weight_decay=0.0)
    sched = get_cosine_schedule_with_warmup(
        opt, int(cfg.warmup_ratio * n_updates), n_updates)

    print(f"\n[train] {len(schedule)} examples, grad_accum {cfg.grad_accum} "
          f"-> {n_updates} optimiser steps, lr {cfg.lr}, beta_KL {cfg.beta_kl}, "
          f"clip {cfg.clip_eps}")
    if dry_run:
        print("[train] --dry-run: stopping before the first forward pass.")
        return {"dry_run": True, "n_examples": len(schedule), "n_updates": n_updates}

    # =================================================================================
    # PRE-PASS: log-probabilities under the policy AS IT IS RIGHT NOW, cached.
    #
    # THIS IS WHAT MAKES THE RATIO AND THE KL MEAN ANYTHING, and getting it wrong is
    # silent in both directions.
    #
    #   pi_old  must be the policy that GENERATED the rollout. Recomputing it from the
    #           live weights inside the loop makes rho = exp(lp - lp.detach()) = 1.0
    #           exactly, forever: the clipping never engages, and `rho`/`clip` in the
    #           log print 1.000 and 0.00% no matter how stale the data has become. The
    #           gradient still happens to be right (it reduces to REINFORCE), so nothing
    #           looks broken -- there is simply no staleness protection at all.
    #
    #   pi_ref  must be the policy at RL start, which is the SFT adapter. Using
    #           model.disable_adapter() gives the BASE model instead, so the KL term
    #           pulls the policy back toward the un-finetuned weights and actively
    #           fights the SFT initialisation it was started from.
    #
    # At this instant both are the same thing -- the initial policy -- so ONE cached
    # tensor serves both, the reference is correct by construction, and the training loop
    # drops from three forward passes per example to one.
    # =================================================================================
    print(f"\n[ref] caching reference log-probs for {len(prepared)} turns "
          f"(one no-grad forward each; this is what the ratio and the KL are measured "
          f"against)")
    lp0: List = [None] * len(prepared)
    was_training = model.training
    model.eval()
    t_ref = time.time()
    with torch.no_grad():
        for j, (_t, ids, clen) in enumerate(prepared):
            input_ids = torch.tensor([ids], dtype=torch.long, device=dev)
            attn = torch.ones_like(input_ids)
            # kept on CPU: comp_len floats per turn is a few KB, and the GPU needs its
            # memory for the backward pass.
            lp0[j] = seq_logprobs(model, input_ids, attn, clen, torch=torch,
                                  keep_supported=keep_supported).detach().float().cpu()
            if (j + 1) % 200 == 0:
                print(f"[ref] {j+1}/{len(prepared)}  "
                      f"({(time.time()-t_ref)/60:.1f}m)", flush=True)
    if was_training:
        model.train()
    print(f"[ref] done in {(time.time()-t_ref)/60:.1f} min")

    hist = defaultdict(list)
    t0 = time.time()
    opt.zero_grad(set_to_none=True)
    acc = 0
    step = 0

    for i, (j, turn, ids, clen, adv) in enumerate(schedule):
        input_ids = torch.tensor([ids], dtype=torch.long, device=dev)
        attn = torch.ones_like(input_ids)

        # ONE forward. pi_old and pi_ref both come from the cache above, so the ratio
        # measures real drift from the generating policy and the KL is against the SFT
        # adapter rather than the base model.
        ref = lp0[j].to(dev)
        lp = seq_logprobs(model, input_ids, attn, clen, torch=torch,
                          keep_supported=keep_supported)
        lp_old = ref
        lp_ref = ref
        ratio = torch.exp(lp - lp_old)
        a = torch.tensor(float(adv), device=dev, dtype=ratio.dtype)
        unclipped = ratio * a
        clipped = torch.clamp(ratio, 1.0 - cfg.clip_eps, 1.0 + cfg.clip_eps) * a
        pg = -torch.min(unclipped, clipped).mean()

        # k3: unbiased, always non-negative, and far lower variance than (logp_ref - logp).
        #
        # WHICH TAIL DRIVES THIS, AND WHY max_ratio CANNOT SEE IT
        # lp_old == lp_ref here, so d = -log(rho) and k3 = 1/rho + log(rho) - 1. The KL is
        # therefore driven by tokens whose probability COLLAPSED, not by tokens that grew:
        #     rho 14.3  -> k3   1.7        <- the max_ratio that was being logged
        #     rho 0.01  -> k3  94
        #     rho 0.001 -> k3 992
        # A run reported mean_kl 321 with mean_ratio 0.992 and clipfrac 3.9%: almost every
        # token sat still while a few collapsed by three or four orders of magnitude. The
        # only diagnostic in the summary pointed at the other tail, so the number looked
        # like uniform divergence and was not. ratio_min and the k3 percentiles below are
        # what make that visible.
        d = lp_ref - lp

        # REPORTED, unclamped: the diagnostics must not flatter the run.
        with torch.no_grad():
            k3_all = torch.exp(d) - d - 1.0

        # PENALISED, clamped. d enters the loss through exp(d), so its gradient is also
        # exponential: one collapsed token contributes a gradient ~1/rho^2 and the KL
        # penalty -- the term whose job is to hold the policy near the reference -- becomes
        # the largest destabilising force in the update. Clamping d caps any single token's
        # contribution (kl_clamp 5 -> at most 143) and leaves everything inside the trust
        # region untouched, because d is under 1 there.
        d_pen = d.clamp(max=cfg.kl_clamp) if cfg.kl_clamp > 0 else d
        kl = (torch.exp(d_pen) - d_pen - 1.0).mean()

        loss = (pg + cfg.beta_kl * kl) / cfg.grad_accum
        loss.backward()
        acc += 1

        with torch.no_grad():
            hist["pg"].append(float(pg))
            hist["kl"].append(float(k3_all.mean()))          # unclamped, for reporting
            hist["kl_pen"].append(float(kl))                 # what the loss actually used
            hist["ratio"].append(float(ratio.mean()))
            hist["ratio_max"].append(float(ratio.max()))
            hist["ratio_min"].append(float(ratio.min()))     # THE tail that drives KL
            flat = k3_all.flatten()
            hist["kl_max"].append(float(flat.max()))
            if flat.numel() > 1:
                q = torch.quantile(flat.float(),
                                   torch.tensor([0.5, 0.95], device=flat.device))
                hist["kl_p50"].append(float(q[0]))
                hist["kl_p95"].append(float(q[1]))
            # a token whose probability fell by 20x or more: the population to count
            hist["collapsed"].append(float((ratio < 0.05).float().mean()))
            hist["clipfrac"].append(float(((ratio - 1.0).abs() > cfg.clip_eps)
                                          .float().mean()))
            hist["loss"].append(float(pg + cfg.beta_kl * kl))

        if acc >= cfg.grad_accum:
            torch.nn.utils.clip_grad_norm_(
                [p for p in model.parameters() if p.requires_grad], 1.0)
            opt.step()
            sched.step()
            opt.zero_grad(set_to_none=True)
            acc = 0
            step += 1
            if step % max(1, log_every) == 0:
                w = hist["loss"][-cfg.grad_accum * log_every:]
                r = hist["ratio"][-cfg.grad_accum * log_every:]
                k = hist["kl"][-cfg.grad_accum * log_every:]
                cf = hist["clipfrac"][-cfg.grad_accum * log_every:]
                mean_rho = sum(r) / len(r)
                warn = ""
                if mean_rho > 1.3 or mean_rho < 0.77:
                    # The data was generated by a policy this one has now left behind.
                    # Training further on it optimises the wrong objective; the fix is a
                    # fresh rollout, not more steps.
                    warn = "   <-- STALE: roll out again rather than training longer"
                mean_k = sum(k) / len(k)
                print(f"[train] step {step}/{n_updates}  loss {sum(w)/len(w):+.4f}  "
                      f"KL {mean_k:.4f}  rho {mean_rho:.3f}  "
                      f"clip {sum(cf)/len(cf):.2%}  "
                      f"{(time.time()-t0)/60:.1f}m{warn}", flush=True)

                # ---- TRUST REGION. The adapter is NOT saved past this point. ----------
                #
                # A run at lr=2e-5 reached mean_kl 321 and saved anyway. The output path
                # is DERIVED from the ablation, so that destroyed adapter silently
                # replaced a working one under the same name, and the only way to notice
                # was to read grpo_summary.json afterwards. Overwriting a good adapter
                # with a diverged one is strictly worse than producing nothing, so this
                # stops before the save.
                #
                # Bands measured on this task, gemma3-27b, ~265 updates:
                #   KL < 0.005   inert. lora_B stays ~1e-5, decisions do not move
                #   KL 0.01-0.1  the usable band
                #   KL > 1       the policy is leaving the reference behind
                #   KL > 10      diverged; completions degrade into noise
                if cfg.kl_max > 0 and mean_k > cfg.kl_max:
                    raise SystemExit(
                        f"\n[FATAL] DIVERGED — mean KL {mean_k:.2f} over the last window "
                        f"exceeds --kl-max {cfg.kl_max:g}.\n"
                        f"        Stopped at step {step}/{n_updates}. NOTHING WAS SAVED, so "
                        f"whatever adapter\n"
                        f"        was at {out_dir}\n"
                        f"        is untouched.\n\n"
                        f"        lr={cfg.lr:g} is too high for this adapter. Measured on "
                        f"this task:\n"
                        f"          lr 1e-6   mean_kl 0.0009   inert, decisions unchanged\n"
                        f"          lr 2e-5   mean_kl 321      diverged\n"
                        f"        A 20x change in lr moved KL by 5 orders of magnitude, so "
                        f"the useful\n"
                        f"        setting is close to the low end. Try lr 3e-6, then 5e-6, "
                        f"and keep the\n"
                        f"        run whose mean_kl lands in 0.01-0.1.\n\n"
                        f"        If a smaller lr is still inert, raise the number of "
                        f"UPDATES instead\n"
                        f"        (lower GRAD_ACCUM) rather than the step size, and check "
                        f"that stage A\n"
                        f"        produced groups with reward variance — a group whose "
                        f"members all score\n"
                        f"        the same contributes no gradient at any learning rate.")

    if acc:
        opt.step()
        opt.zero_grad(set_to_none=True)
        step += 1

    os.makedirs(out_dir, exist_ok=True)
    model.save_pretrained(out_dir)
    tok.save_pretrained(out_dir)

    def _m(xs):
        return sum(xs) / len(xs) if xs else float("nan")

    summary = {"model": model_key, "out_dir": out_dir, "n_examples": len(schedule),
               "n_updates": step, "minutes": (time.time() - t0) / 60,
               "mean_loss": _m(hist["loss"]), "mean_kl": _m(hist["kl"]),
               "mean_kl_penalised": _m(hist["kl_pen"]),
               "mean_ratio": _m(hist["ratio"]), "max_ratio": max(hist["ratio_max"] or [0]),
               # THE TAIL THAT DRIVES KL. k3 = 1/rho + log(rho) - 1, so the collapsed
               # tokens are the whole story and max_ratio points the wrong way.
               "min_ratio": min(hist["ratio_min"] or [0]),
               "kl_p50": _m(hist["kl_p50"]), "kl_p95": _m(hist["kl_p95"]),
               "kl_max": max(hist["kl_max"] or [0]),
               "collapsed_frac": _m(hist["collapsed"]),
               "mean_clipfrac": _m(hist["clipfrac"]),
               "lr": cfg.lr, "beta_kl": cfg.beta_kl, "clip_eps": cfg.clip_eps,
               "kl_clamp": cfg.kl_clamp, "grad_accum": cfg.grad_accum,
               "intra_steps": intra_steps}
    with open(os.path.join(out_dir, "grpo_summary.json"), "w") as f:
        json.dump(summary, f, indent=2)

    print("\n" + "=" * 92)
    print(f"GRPO COMPLETE — {model_key}")
    print("=" * 92)
    print(f"  {step} optimiser steps in {summary['minutes']:.1f} min")
    print(f"  mean KL to reference   {summary['mean_kl']:.4f}")
    print(f"  mean importance ratio  {summary['mean_ratio']:.3f} "
          f"(max {summary['max_ratio']:.3f})")
    print(f"  clipped fraction       {summary['mean_clipfrac']:.1%}")
    print()
    print("  HOW TO READ THESE THREE NUMBERS")
    print("    KL should be small and RISING slowly. Flat at ~0 means the adapter is not")
    print("    moving (lr too low, or every advantage is 0). Above ~0.1 the policy has")
    print("    left the reference and the completions are about to stop parsing.")
    print("    The mean ratio starts at 1.0 and drifts up as the data goes stale. Past")
    print("    ~1.3, shorten the iteration: roll out again rather than training longer.")
    print("    A clipped fraction above ~30% means most updates are being throttled, so")
    print("    the step size is fighting the clip -- lower the learning rate instead.")
    print(f"\n[saved] {out_dir}")
    return summary


# ======================================================================================
def main() -> int:
    p = argparse.ArgumentParser(description="GRPO with multi-agent credit assignment")
    p.add_argument("--model", required=True, choices=sorted(C.MODELS))
    p.add_argument("--ablation", required=True, choices=sorted(C.ABL))
    p.add_argument("--rollout-dir", dest="roll_dir", required=True)
    p.add_argument("--out-dir", dest="out_dir", default="")
    p.add_argument("--init-adapter", dest="init_adapter", default="",
                   help="the SFT adapter to continue from. Strongly recommended: GRPO "
                        "from a base policy that cannot emit the JSON schema spends its "
                        "whole budget learning the format.")
    p.add_argument("--agent", default="",
                   help="train ONE agent's adapter (per-agent ablations). Omit for the "
                        "shared adapter.")
    p.add_argument("--lr", type=float, default=C.GRPO.lr)
    p.add_argument("--beta-kl", dest="beta_kl", type=float, default=C.GRPO.beta_kl)
    p.add_argument("--clip-eps", dest="clip_eps", type=float, default=C.GRPO.clip_eps)
    p.add_argument("--kl-clamp", dest="kl_clamp", type=float, default=C.GRPO.kl_clamp,
                   help="cap on d=-log(rho) in the KL PENALTY (reporting stays "
                        "unclamped); 0 disables")
    p.add_argument("--kl-max", dest="kl_max", type=float, default=C.GRPO.kl_max,
                   help="abort WITHOUT SAVING if the windowed mean KL exceeds this "
                        "(0 disables). Stops a diverged run from overwriting a good "
                        "adapter under the derived name.")
    p.add_argument("--grad-accum", dest="grad_accum", type=int, default=C.GRPO.grad_accum)
    p.add_argument("--max-seq-len", dest="max_seq_len", type=int,
                   default=C.GRPO.max_seq_len)
    p.add_argument("--intra-steps", dest="intra_steps", type=int, default=1,
                   help="M-GRPO: optimiser steps on the agent-local advantage per step "
                        "on the shared one. 1 = coupled.")
    p.add_argument("--max-steps", dest="max_steps", type=int, default=0)
    p.add_argument("--log-every", dest="log_every", type=int, default=10)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--dry-run", dest="dry_run", action="store_true",
                   help="load, tokenise, report, and stop before the first forward. "
                        "Catches a template or length problem in a minute instead of "
                        "three hours in.")
    a = p.parse_args()

    ab = C.ABL[a.ablation]
    cfg = C.GRPOConfig(lr=a.lr, beta_kl=a.beta_kl, clip_eps=a.clip_eps,
                       grad_accum=a.grad_accum, max_seq_len=a.max_seq_len, seed=a.seed,
                       kl_max=a.kl_max, kl_clamp=a.kl_clamp)
    intra = a.intra_steps
    if ab.credit == "mgrpo" and intra <= 1:
        intra = 2
        print("[mgrpo] this ablation is M-GRPO and --intra-steps was 1; raising to 2. "
              "With coupled updates J is identical to H and the row measures nothing.")

    agents = (a.agent,) if a.agent else ()
    turns, stats = load_turns(a.roll_dir, agents=agents)
    if not turns:
        raise SystemExit(
            f"[FATAL] no usable turns in {a.roll_dir}.\n"
            f"        {stats.get('n_dropped', 0)} of {stats.get('n_rollouts', 0)} "
            f"rollouts were in groups with no reward variance. If that is most of them, "
            f"the rollout temperature was too low or the episodes are too easy — see the "
            f"diagnosis v7_score_rollouts.py prints.")

    out_dir = a.out_dir or C.adapter_dir(a.model, ab.stage or "grpo",
                                         a.agent or None)
    train(turns, a.model, out_dir, init_adapter=a.init_adapter, cfg=cfg,
          intra_steps=intra, max_steps=a.max_steps, log_every=a.log_every,
          dry_run=a.dry_run)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
