#!/usr/bin/env python3
"""
train_grpo.py — GRPO on multi-agent cascade trajectories, with pluggable credit
assignment.

WHY THIS IS HAND-WRITTEN AND NOT TRL's GRPOTrainer
=======================================================================================
Two reasons, and the second one is the whole package.

  1. MEMORY. TRL's GRPOTrainer generates inside the training loop. Co-locating vLLM and a
     4-bit gemma3-27b trainer on one 40 GiB card is not possible, and its server mode
     wants a second GPU serving full-time. Your allocation is one or two cards, so the
     rollout and the update have to be SEPARATE PBS stages -- which is what
     v7_score_rollouts.py + this file are. v7 does not generate rollouts at all:
     llim_agents_v4_SFT_DPO already sampled them.

  2. CREDIT. GRPOTrainer assigns one advantage per completion. This trainer assigns one
     advantage per (trajectory, AGENT), from rl_credit. There is no way to express
     "the leader gets +1.4 and the instruction worker gets -0.2 on the same trajectory"
     through a reward function that returns a scalar per completion, and that expression
     is the contribution.

WHAT "OFFLINE" COSTS, STATED PLAINLY
    The rollouts were generated by the policy at the START of the iteration, and the
    update moves the policy away from it. So after the first optimiser step the data is
    off-policy, and the importance ratio rho = pi_theta / pi_old is doing real work rather
    than sitting at 1. That is why this runs ONE epoch per iteration with PPO-style
    clipping, and why GRPO.iterations exists: three short on-policy-ish rounds beat one
    long stale one. The run prints the mean and the max ratio every epoch; if the mean
    drifts past about 1.3 the data is too stale and the iteration should be shortened.

THE OBJECTIVE
    Per completion token t, with rho_t = exp(logpi_theta(t) - logpi_old(t)):

        L = - E_t [ min(rho_t * A, clip(rho_t, 1-eps, 1+eps) * A) ] + beta * KL_t

    A is the agent's advantage for this trajectory, constant across the completion's
    tokens. KL_t is the unbiased k3 estimator against the FROZEN REFERENCE, which here is
    the same model with the LoRA adapter switched off -- so the reference costs no extra
    weights, only a second forward pass.

    Tokens are weighted equally within a completion and completions equally within the
    batch. That is the "Dr. GRPO" length-unbiased choice: the token-mean-then-sequence-mean
    form gives long completions more influence per token, which on this task rewards the
    leader for writing longer explanations rather than better ones.
"""

